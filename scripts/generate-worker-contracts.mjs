const defs = schema.$defs, check = process.argv.includes('--check');
const literal = value => JSON.stringify(value);
function type(s, python = false) {
  if (s.$ref) return s.$ref.split('/').at(-1);
  if (s.anyOf) return s.anyOf.map(item => type(item, python)).join(' | ');
  if ('const' in s || s.enum) { const values = 'const' in s ? [s.const] : s.enum; return python ? `Literal[${values.map(literal).join(', ')}]` : values.map(literal).join(' | '); }
  if (s.format === 'uuid') return python ? 'UUID' : 'string';
  if (s.type === 'array') return python ? `list[${nestedType(s.items)}]` : `(${type(s.items)})[]`;
  return (python ? { string: 'str', integer: 'int', boolean: 'bool', null: 'None', object: 'dict[str, Any]' } : { string: 'string', integer: 'number', boolean: 'boolean', null: 'null', object: 'Record<string, unknown>' })[s.type];
}
function nestedType(s) {
  const options = [];
  for (const [json, python] of Object.entries({minLength:'min_length',maxLength:'max_length',minItems:'min_length',maxItems:'max_length',minimum:'ge',maximum:'le',pattern:'pattern'})) if (json in s) options.push(`${python}=${literal(s[json])}`);
  if (['string','integer'].includes(s.type) && !s.format && !s.enum) options.push('strict=True');
  return options.length ? `Annotated[${type(s, true)}, Field(${options.join(', ')})]` : type(s, true);
}
