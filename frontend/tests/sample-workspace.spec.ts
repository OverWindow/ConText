test('signed-in sample uses real repositories with synthetic AI, persists drafts and chats and opens citations', async ({ page }) => {
  const user = { id: '00000000-0000-0000-0000-000000000001', email: 'test@example.test', aud: 'authenticated', role: 'authenticated', app_metadata: {}, user_metadata: {} };
  const encode = (value: object) => Buffer.from(JSON.stringify(value)).toString('base64url');
  const token = `${encode({ alg: 'HS256', typ: 'JWT' })}.${encode({ sub: user.id, exp: Math.floor(Date.now() / 1000) + 3600, role: 'authenticated' })}.test-signature`;
  await page.context().addCookies([{ name: 'sb-127-auth-token', value: 'base64-' + encode({ access_token: token, refresh_token: 'test-refresh', expires_at: Math.floor(Date.now() / 1000) + 3600, expires_in: 3600, token_type: 'bearer', user }), domain: 'localhost', path: '/' }]);
  const requests: { task: string; sources: { id: string; document_title: string }[] }[] = [];
  await page.route('http://localhost:3102/api/ai/**', async route => {
    const request = route.request(); expect(request.headers().authorization).toBe(`Bearer ${token}`);
    if (request.url().endsWith('/context')) {
      const input = request.postDataJSON(); requests.push(input);
      expect(input.sources.length).toBeGreaterThan(0);
      expect(input.sources.every((source: { id: string }) => source.id.startsWith('sample-'))).toBe(true);
      const source = input.sources[0];
      await route.fulfill({ json: input.task === 'write' ? { content: { title: '모아오더 샘플 소개서', blocks: [{ id: 'intro', type: 'paragraph', text: '하루랩 자료로 작성한 소개서입니다.', source_ids: [source.id] }] }, checks: [] } : { claims: [{ text: '모아오더 요구사항에 근거한 답변입니다.', source_ids: [source.id] }], insufficient: false } });
    } else if (request.url().endsWith('/models')) await route.fulfill({ json: [{ id: 'sample-test-model', name: '시연 모델' }] });
    else await route.fulfill({ json: { mode: 'managed', model: 'sample-test-model', has_personal_key: false, personal_key_storage_available: true } });
  });
  await page.goto('/preview');
  await page.getByRole('button', { name: 'AI 연결 설정', exact: true }).click();
  await expect(page.getByRole('combobox', { name: 'AI 모델', exact: true })).toHaveValue('sample-test-model');
  await page.getByRole('button', { name: 'AI 설정 닫기' }).click();
  await page.getByRole('button', { name: 'AI 문서 작성', exact: true }).click();
  await page.getByRole('textbox', { name: '어떤 문서를 만들까요?' }).fill('모아오더 제품 소개서를 작성해줘');
  await page.getByRole('button', { name: 'AI 초안 만들기' }).click();
  await expect(page.getByRole('textbox', { name: '문서 제목' })).toHaveValue('모아오더 샘플 소개서');
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: 'MD', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('모아오더 샘플 소개서.md');
  await page.getByRole('button', { name: '문서 작성 닫기' }).click();
  await page.getByRole('button', { name: 'AI 채팅', exact: true }).click();
  const chat = page.getByRole('complementary', { name: 'AI 채팅과 문서 검색' });
  await chat.getByRole('textbox', { name: '문서 질문', exact: true }).fill('모아오더 제품 요구사항이 뭐야?');
  await chat.getByRole('button', { name: '질문 보내기' }).click();
  await expect(chat).toContainText('모아오더 요구사항에 근거한 답변');
  await chat.getByRole('button', { name: /근거 보기/ }).first().click();
  await chat.getByRole('button', { name: '인용한 수정 이력 열기' }).first().click();
  await expect(page.getByRole('dialog')).toContainText('모아오더');
  await page.getByRole('button', { name: '미리보기 닫기' }).click();
  await page.reload();
  await page.getByRole('button', { name: 'AI 문서 작성', exact: true }).click();
  await page.getByRole('button', { name: '모아오더 샘플 소개서', exact: true }).click();
  await expect(page.locator('.ce-paragraph')).toContainText('하루랩 자료로 작성한 소개서');
  await page.getByRole('button', { name: '문서 작성 닫기' }).click();
  await page.getByRole('button', { name: 'AI 채팅', exact: true }).click();
  await chat.getByRole('combobox', { name: '대화 기록' }).selectOption({ label: '모아오더 제품 요구사항이 뭐야?' });
  await expect(chat).toContainText('모아오더 요구사항에 근거한 답변');
  expect(requests.map(input => input.task)).toEqual(['write', 'chat']);
});
test('sample library reads images, HWPX, spreadsheet tables and nested text without a backend',async({page})=>{
  await page.goto('/preview');
  for(const name of ['화면설계_모바일재고.png','주간업무보고_2026-10-23.hwpx','운영예산_2026Q4.xlsx','한글_日本語_English.txt','빈문서.txt']) {
    await page.getByRole('button',{name:'문서 관리',exact:true}).click();
    await page.getByRole('textbox',{name:'관리할 파일 검색'}).fill(name);
    await page.getByRole('button',{name,exact:true}).click();
    const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible();
    if(name.endsWith('.png'))await expect.poll(()=>dialog.locator('img').evaluate((img:HTMLImageElement)=>img.naturalWidth)).toBeGreaterThan(0);
    else if(name.endsWith('.xlsx'))await expect(dialog.getByRole('table').first()).toBeVisible();
    else if(name==='빈문서.txt')await expect(dialog).toContainText('내용이 없는 빈 샘플');
    else await expect(dialog.locator('.text-block').first()).toBeVisible();
    await page.getByRole('button',{name:'미리보기 닫기'}).click();
  }
});
