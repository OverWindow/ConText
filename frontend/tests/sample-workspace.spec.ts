test('sample edits documents and canvas, restores after reload and resets without touching AI work', async ({ page }) => {
  await page.goto('/preview');
  const file = page.getByTestId('file-제품요구사항_v1.2.md');
  await file.locator('.paper-caption').dblclick();
  await page.getByRole('button', { name: '본문 수정', exact: true }).click();
  const editor = page.getByRole('dialog', { name: /샘플 본문 편집/ });
  await editor.getByRole('textbox', { name: '샘플 문서 제목' }).fill('시연용 제품 요구사항');
  await editor.locator('.ce-paragraph[contenteditable="true"]').first().fill('시연수정표식: 신규 출시 목표는 2030년입니다.');
  await editor.getByRole('button', { name: '샘플 저장', exact: true }).click();
  await expect(editor).toBeHidden();
  await expect(page.getByRole('dialog')).toContainText('시연수정표식');
  await page.getByRole('button', { name: '미리보기 닫기' }).click();
  await page.getByRole('button', { name: '캔버스 수정', exact: true }).click();
  await page.getByRole('button', { name: '텍스트 추가', exact: true }).click();
  await page.getByRole('textbox', { name: '캔버스 텍스트 내용', exact: true }).fill('샘플에서 작성한 시연 메모');
  await page.getByRole('button', { name: '캔버스 수정 완료', exact: true }).click();
  await page.reload();
  await page.getByRole('button', { name: '문서 관리', exact: true }).click();
  await page.getByRole('textbox', { name: '관리할 파일 검색' }).fill('제품요구사항_v1.2.md');
  await page.getByRole('button', { name: '제품요구사항_v1.2.md', exact: true }).click();
  await expect(page.getByRole('dialog')).toContainText('시연수정표식');
  await page.getByRole('button', { name: '미리보기 닫기' }).click();
  await expect.poll(() => page.evaluate(() => {
    const key = Object.keys(localStorage).find(key => key.startsWith('context:sample-workspace:'))!;
    return JSON.parse(localStorage.getItem(key)!).items.some((item: { deleted: boolean; value: { text?: string } }) => !item.deleted && item.value.text === '샘플에서 작성한 시연 메모');
  })).toBe(true);
  await page.getByRole('button', { name: '샘플 초기화', exact: true }).click();
  await page.getByRole('button', { name: '초기화 확인', exact: true }).click();
  await page.getByRole('button', { name: '문서 관리', exact: true }).click();
  await page.getByRole('textbox', { name: '관리할 파일 검색' }).fill('제품요구사항_v1.2.md');
  await page.getByRole('button', { name: '제품요구사항_v1.2.md', exact: true }).click();
  await expect(page.getByRole('dialog')).not.toContainText('시연수정표식');
  await page.getByRole('button', { name: '미리보기 닫기' }).click();
  await page.getByRole('button', { name: '새 텍스트 파일 만들기' }).click();
  await page.getByRole('textbox', { name: '이름', exact: true }).fill('새 시연 자료.md');
  await page.getByRole('button', { name: '파일 만들기', exact: true }).click();
  const newEditor = page.getByRole('dialog', { name: /샘플 본문 편집/ });
  await newEditor.locator('.ce-paragraph[contenteditable="true"]').fill('새 샘플 파일에 저장한 본문');
  await newEditor.getByRole('button', { name: '샘플 저장', exact: true }).click();
  await expect(newEditor).toBeHidden();
  await expect(page.getByRole('dialog')).toContainText('새 샘플 파일에 저장한 본문');
});
