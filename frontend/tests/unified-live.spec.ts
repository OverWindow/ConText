import { expect, test } from '@playwright/test';
const origin = 'http://127.0.0.1:18003';
test('browser shared UI persists files, folders, drafts and chat through real Node/Postgres/S3', async ({ page, request }, info) => {
    const configResponse = await request.get(`${origin}/__fixture/config`);
    expect(configResponse.ok()).toBe(true);
    const fixture = await configResponse.json();
    const subject = fixture.user.auth_user_id, encode = (value: object) => Buffer.from(JSON.stringify(value)).toString('base64url');
    const user = { id: subject, email: fixture.user.email, aud: 'authenticated', role: 'authenticated', app_metadata: {}, user_metadata: {} };
    await page.context().addCookies([{ name: 'sb-127-auth-token', value: 'base64-' + encode({ access_token: fixture.token, refresh_token: 'test-refresh', expires_at: Math.floor(Date.now() / 1000) + 3600, expires_in: 3600, token_type: 'bearer', user }), domain: 'localhost', path: '/' }]);
    const calls: string[] = [], streams: number[] = [];
    page.on('response', response => { if (new URL(response.url()).pathname.endsWith('/events')) streams.push(response.status()); });
    await page.route('http://localhost:3102/v2/**', async (route) => {
        const req = route.request(), url = new URL(req.url());
        calls.push(`${req.method()} ${url.pathname}`);
        if (url.pathname.endsWith('/events')) { await route.continue({ url: `${origin}${url.pathname}${url.search}` }); return; }
        const response = await route.fetch({ url: `${origin}${url.pathname}${url.search}` });
        await route.fulfill({ response, headers: { ...response.headers(), 'access-control-allow-origin': '*' } });
    });
    await page.route('http://127.0.0.1:15002/**', async (route) => {
        expect(route.request().headers().authorization).toBeUndefined();
        const response = await route.fetch();
        await route.fulfill({ response, headers: { ...response.headers(), 'access-control-allow-origin': '*' } });
    });
    await page.goto('/workspaces');
    await expect(page.getByRole('button', { name: '계정 관리', exact: true })).toBeVisible();
    await expect(page.locator('[data-application-home="shared"]')).toBeVisible();
    await expect(page.getByRole('navigation')).toHaveCount(0);
    await expect.poll(() => page.locator('.application-home-brand img').evaluateAll(images => images.every(image => (image as HTMLImageElement).complete && (image as HTMLImageElement).naturalWidth > 0))).toBe(true);
    await page.screenshot({ path: `test-results/application-web-home-${info.project.name}.png` });
    const name = `Browser ${info.project.name} ${Date.now()}`;
    await page.getByRole('textbox', { name: '워크스페이스 이름' }).fill(name);
    await page.getByRole('button', { name: '워크스페이스 만들기', exact: true }).click();
    await page.waitForURL(/\/workspaces\/[a-f0-9-]{36}$/);
    const workspaceId = page.url().split('/').at(-1)!;
    await expect(page.getByRole('heading').filter({ hasText: name })).toBeVisible();
    await expect.poll(() => streams.includes(200)).toBe(true);
    if (!await page.getByRole('button', { name: '새 폴더', exact: true }).isVisible()) await page.getByRole('button', { name: '워크스페이스 설정', exact: true }).click(); await page.getByRole('button', { name: '새 폴더', exact: true }).click();
    await page.getByRole('textbox', { name: '이름', exact: true }).fill('실제 공유 폴더');
    await page.getByRole('button', { name: '확인', exact: true }).click();
    await expect(page.getByRole('dialog', { name: '새 폴더' })).toHaveCount(0);
    await page.getByRole('button', { name: '새 텍스트 파일 만들기', exact: true }).click();
    await page.getByRole('textbox', { name: '이름', exact: true }).fill('브라우저.md');
    await page.getByRole('button', { name: '파일 만들기', exact: true }).click();
    await expect(page.getByRole('dialog', { name: '새 텍스트 파일' })).toHaveCount(0);
    await page.getByRole('button', { name: '텍스트 편집 닫기' }).click();
    await page.getByRole('button', { name: '문서 관리', exact: true }).click();
    await page.getByRole('button', { name: '브라우저.md', exact: true }).click();
    await page.getByRole('button', { name: '텍스트 편집', exact: true }).click();
    await page.getByRole('textbox', { name: '원본 텍스트' }).fill('브라우저에서 저장한 실제 공유 원본');
    await page.getByRole('button', { name: '원본 저장', exact: true }).click();
    await expect(page.getByText('저장됨', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '텍스트 편집 닫기' }).click();
    const headers = { Authorization: `Bearer ${fixture.token}` }, bootResponse = await request.get(`${origin}/v2/workspaces/${workspaceId}/bootstrap`, { headers }), boot = await bootResponse.json();
    const entry = Object.values(boot.state.entries).find((value) => (value as {
        name: string;
    }).name === '브라우저.md') as {
        id: string;
        document_id: string;
    };
    const document = boot.state.documents[entry.document_id];
    expect(Object.values(boot.state.versions).filter(value => (value as {
        document_id: string;
    }).document_id === document.id)).toHaveLength(2);
    const download = await request.get(`${origin}/v2/workspaces/${workspaceId}/versions/${document.content_head_id}/download`, { headers });
    const bytes = await request.get((await download.json()).url);
    expect(await bytes.text()).toBe('브라우저에서 저장한 실제 공유 원본');
    await page.reload();
    await expect(page.getByRole('heading').filter({ hasText: name })).toBeVisible();
    await expect.poll(() => streams.includes(200)).toBe(true);
    await page.getByRole('button', { name: '문서 관리', exact: true }).click();
    await expect(page.getByRole('button', { name: '실제 공유 폴더', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '문서 관리 닫기', exact: true }).click();
    await page.getByRole('button', { name: 'AI 문서 작성', exact: true }).click();
    await page.getByRole('button', { name: '직접 작성하기', exact: true }).click();
    await page.getByRole('textbox', { name: '문서 제목' }).fill('실제 공유 초안');
    await page.locator('.ce-paragraph[contenteditable="true"]').fill('실제 공유 초안의 본문');
    await page.getByRole('button', { name: '저장', exact: true }).click();
    await expect(page.getByText('저장됨 · 버전 2', { exact: true })).toBeVisible();
    await page.getByRole('button', { name: '문서 작성 닫기' }).click();
    await page.getByRole('button', { name: 'AI 채팅', exact: true }).click();
    await page.getByRole('textbox', { name: '문서 질문' }).fill('공유 자료를 설명해줘');
    await page.getByRole('button', { name: '질문 보내기' }).click();
    await expect(page.getByRole('article', { name: 'AI 답변', exact: true })).toContainText('Shared result survives retry.', { timeout: 30000 });
    const after = (await (await request.get(`${origin}/v2/workspaces/${workspaceId}/bootstrap`, { headers })).json()).state;
    expect(Object.values(after.drafts).some(value => (value as {
        title: string;
    }).title === '실제 공유 초안')).toBe(true);
    expect(Object.values(after.chat_messages)).toHaveLength(2);
    expect(calls.some(path => path.endsWith('/commands'))).toBe(true);
    await page.getByRole('button', { name: 'AI 채팅 접기', exact: true }).click();
    await expect(page.locator('.chat-drawer')).toBeHidden();
    await page.getByRole('button', { name: '전체 보기', exact: true }).click();
    await page.screenshot({ path: `test-results/application-web-live-${info.project.name}.png` });
    await page.locator('.cloud-control > button').click();
    await page.getByRole('region', { name: '동기화 상태', exact: true }).getByRole('button', { name: '워크스페이스 삭제', exact: true }).click();
    const deletion = page.getByRole('dialog', { name: '워크스페이스 삭제', exact: true });
    await deletion.getByRole('textbox').fill(name);
    await deletion.getByRole('button', { name: '워크스페이스 삭제', exact: true }).click();
    await page.waitForURL('**/workspaces');
    const tombstone = await (await request.get(`${origin}/v2/workspaces/${workspaceId}/bootstrap`, { headers })).json();
    expect(tombstone.state.workspace.deleted_at).toBeTruthy();
    expect((await (await request.get(`${origin}/v2/workspaces`, { headers })).json()).workspaces.some((item: { id: string }) => item.id === workspaceId)).toBe(false);
    await expect(page.getByRole('button', { name: '계정 관리', exact: true })).toBeVisible();
});
